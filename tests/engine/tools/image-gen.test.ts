import { beforeEach, describe, expect, it } from 'bun:test'

import type { FigmaAPI } from '@open-pencil/core'
import { ALL_TOOLS } from '@open-pencil/core'
import {
  generateImage,
  registerGeneratedImageProvider,
  setActiveGeneratedImageProvider,
  type GeneratedImageProvider
} from '@open-pencil/core/tools'

import { getTool, setupToolTest } from '#tests/helpers/tools'

// Minimal valid PNG signature — the renderer never decodes it in these tests.
const IMAGE_BYTES = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x42, 0x42])

function fakeProvider(overrides?: Partial<GeneratedImageProvider>): GeneratedImageProvider {
  return {
    name: 'test-provider',
    generate: async () => IMAGE_BYTES,
    ...overrides
  }
}

async function makePlaceholder(
  figma: FigmaAPI,
  type = 'RECTANGLE',
  name = 'HeroArt'
): Promise<string> {
  const result = (await getTool('create_shape').execute(figma, {
    type,
    name,
    x: 0,
    y: 0,
    width: 400,
    height: 300
  })) as { id?: string }
  return result.id ?? ''
}

describe('generate_image', () => {
  beforeEach(() => {
    setActiveGeneratedImageProvider(null)
  })

  it('is exported but deliberately absent from the static registry', () => {
    // The tool is added to a session only when the active provider can generate
    // images, so it must NOT ship in ALL_TOOLS where every session would see it.
    expect(ALL_TOOLS.some((tool) => tool.name === 'generate_image')).toBe(false)
    expect(generateImage.name).toBe('generate_image')
    expect(generateImage.mutates).toBe(true)
    expect(generateImage.params.requests?.required).toBe(true)
  })

  it('reports an honest error when no provider is configured', async () => {
    const { figma } = setupToolTest()
    const id = await makePlaceholder(figma)
    const result = (await generateImage.execute(figma, {
      requests: JSON.stringify([{ id, prompt: 'a fox' }])
    })) as { error?: string }
    expect(result.error).toContain('not available')
  })

  it('applies generated bytes as an IMAGE fill', async () => {
    registerGeneratedImageProvider(fakeProvider())
    setActiveGeneratedImageProvider('test-provider')
    const { graph, figma } = setupToolTest()
    const id = await makePlaceholder(figma)

    const result = (await generateImage.execute(figma, {
      requests: JSON.stringify([{ id, prompt: 'a fox' }])
    })) as {
      applied: number
      failed: number
      provider: string
      results: Array<{ image?: { imageHash: string } }>
    }

    expect(result.applied).toBe(1)
    expect(result.failed).toBe(0)
    expect(result.provider).toBe('test-provider')

    const hash = result.results[0]?.image?.imageHash
    expect(hash).toBeString()
    // The bytes must reach the document store, or the fill points at nothing.
    expect(graph.images.get(hash as string)).toEqual(IMAGE_BYTES)
    expect(figma.getNodeById(id)?.fills[0]?.imageHash).toBe(hash)
  })

  it('generates a batch in one call and reports partial failure', async () => {
    registerGeneratedImageProvider(fakeProvider())
    setActiveGeneratedImageProvider('test-provider')
    const { figma } = setupToolTest()
    const first = await makePlaceholder(figma, 'RECTANGLE', 'HeroArt')

    const result = (await generateImage.execute(figma, {
      requests: JSON.stringify([
        { id: first, prompt: 'a fox' },
        { id: 'missing:1', prompt: 'a cat' }
      ])
    })) as { applied: number; failed: number }

    expect(result.applied).toBe(1)
    expect(result.failed).toBe(1)
  })

  it('surfaces a provider failure without mutating the document', async () => {
    registerGeneratedImageProvider(
      fakeProvider({
        generate: async () => {
          throw new Error('content policy violation')
        }
      })
    )
    setActiveGeneratedImageProvider('test-provider')
    const { figma } = setupToolTest()
    const id = await makePlaceholder(figma)

    const result = (await generateImage.execute(figma, {
      requests: JSON.stringify([{ id, prompt: 'explicit content' }])
    })) as { results: Array<{ error?: string; image?: unknown }> }

    expect(result.results[0]?.error).toContain('content policy')
    expect(result.results[0]?.image).toBeUndefined()
  })

  it('refuses targets that already have content', async () => {
    registerGeneratedImageProvider(fakeProvider())
    setActiveGeneratedImageProvider('test-provider')
    const { figma } = setupToolTest()
    const parent = await makePlaceholder(figma, 'FRAME', 'Card')
    await getTool('create_shape').execute(figma, {
      type: 'ELLIPSE',
      name: 'Icon',
      parent_id: parent,
      x: 10,
      y: 10,
      width: 40,
      height: 40
    })

    const result = (await generateImage.execute(figma, {
      requests: JSON.stringify([{ id: parent, prompt: 'a fox' }])
    })) as { results: Array<{ error?: string }> }

    expect(result.results[0]?.error).toContain('already has content')
  })

  it('rejects an empty or malformed batch', async () => {
    registerGeneratedImageProvider(fakeProvider())
    setActiveGeneratedImageProvider('test-provider')
    const { figma } = setupToolTest()

    const empty = (await generateImage.execute(figma, { requests: '[]' })) as { error?: string }
    expect(empty.error).toContain('Empty requests')

    const malformed = (await generateImage.execute(figma, { requests: 'not json' })) as {
      error?: string
    }
    expect(malformed.error).toBeDefined()
  })
})
